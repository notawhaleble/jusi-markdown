local jusi = require('jusi_neovim')
local provider = require('jusi_markdown')
local documents = require('jusi_neovim.document')
local surface_url
local open_surface = _G.jusi_neovim_open_surface
_G.jusi_neovim_open_surface = function(buf, url, options)
  surface_url = url
  return open_surface(buf, url, options)
end
assert(vim.fn.exists(':JusiMarkdown') == 2, 'native package did not register command')
local prior = vim.api.nvim_get_current_buf()
vim.api.nvim_buf_set_lines(prior, 0, -1, false, { 'keep unsaved edits' })
local function open(command)
  vim.api.nvim_cmd({ cmd = command:gsub('!$', ''), bang = command:sub(-1) == '!', args = { vim.env.JUSI_TEST_FILE }, magic = { file = false } }, {})
  local buf = vim.api.nvim_get_current_buf()
  assert(vim.wait(10000, function() return vim.b[buf].jusi_buffer_kind == 'web' end), 'worker did not become ready')
  assert(buf ~= prior)
  return buf
end
local disabled = open('JusiMarkdown')
assert(vim.b[disabled].jusi_text_layer == 'off', 'global configuration ignored')
jusi.close(disabled)
provider.setup({ node = vim.env.JUSI_TEST_NODE, text_layer = 'auto' })
provider.setup()
local buf = open('JusiMarkdown')
assert(vim.b[buf].jusi_text_layer == 'auto')
assert(vim.wait(1000, function() return vim.b[buf].jusi_markdown_path == vim.env.JUSI_TEST_FILE end), 'filename metadata missing')
assert(vim.fn.fnamemodify(vim.api.nvim_buf_get_name(buf), ':t'):find(vim.fn.fnamemodify(vim.env.JUSI_TEST_FILE, ':t'), 1, true))
assert(vim.fn.maparg('<CR>', 'n', false, true).desc:match('Markdown follow link'))
assert(vim.fn.maparg('<C-j>', 'n', false, true).desc:match('Markdown follow link'))
local published = vim.system({ vim.env.JUSI_TEST_NODE, vim.env.JUSI_TEST_LAYOUT, surface_url }, { text = true }):wait()
assert(published.code == 0, published.stderr)
local ticket = { bufferId = buf, incarnation = vim.b[buf].jusi_incarnation, sessionId = 'markdown-integration', revision = 1 }
assert(documents.invalidate(ticket))
local done, failure, document
jusi.extract(ticket, function(err, result) failure = err; document = result; done = true end)
assert(vim.wait(10000, function() return done end), 'extraction timeout')
assert(not failure, failure)
assert(documents.commit_worker(ticket, document))
assert(not vim.bo[buf].modifiable)
local text = vim.api.nvim_buf_get_lines(buf, 0, -1, false)
assert(text[1] == 'Hello café' and text[2] == 'Search and yank Привет 文 😀')
assert(vim.api.nvim_buf_get_lines(prior, 0, -1, false)[1] == 'keep unsaved edits')
vim.api.nvim_win_set_cursor(0, { 1, 0 })
vim.cmd('normal! yy')
assert(vim.fn.getreg('"') == 'Hello café\n', 'ordinary Neovim yank failed')
assert(vim.fn.search('Привет', 'W') == 2, 'Unicode search failed')
jusi.navigate()
local newer = vim.tbl_extend('force', ticket, { revision = 2 })
assert(documents.invalidate(newer))
assert(not documents.commit_worker(ticket, document), 'stale publication was accepted')
jusi.close(buf)
local bang = open('JusiMarkdown!')
assert(vim.b[bang].jusi_text_layer == 'off')
assert(vim.api.nvim_buf_get_lines(bang, 0, -1, false)[1] == '')
jusi.close(bang)
require('jusi_neovim.worker').close_all()
print('Markdown native installation, literal paths, worker, read-only buffer, Unicode yank/search, stale publication and bang passed')
vim.cmd('qa!')
