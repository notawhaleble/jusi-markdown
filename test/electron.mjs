async function waitFor(fn) {
  let error;
  for (let i = 0; i < 300; i++) {
    const result = await Promise.resolve().then(fn).catch(e => { error = e; return false; });
    if (result) return result;
    await new Promise(resolve => setTimeout(resolve, 40));
  }
  throw new Error(`${stage}: ${fn.toString()} (${error ?? ''})`);
}
